type VoiceDriver interface {
	Snapshot(context.Context, VoiceConfig) (VoiceSnapshot, error)
	SourceSHA256(context.Context, VoiceConfig, VoicePod) (string, error)
	CanEvict(context.Context, VoiceConfig) error
	RunMedia(context.Context, VoiceConfig, VoicePod, VoiceSession, []byte, func(context.Context) (VoiceEviction, error)) VoiceSession
	Evict(context.Context, VoiceConfig, VoicePod) VoiceEviction
	CleanupTranscripts(context.Context, VoiceConfig, VoicePod, []string, func(TranscriptRef) error, func(TranscriptRef) error) VoiceCleanup
}

func validateSession(s VoiceSession, recovery bool) error {
	if s.Error != "" {
		return fmt.Errorf("Voice media session failed: %s", s.Error)
	}
	if s.TelephoneCalls != 0 || !s.StartSent || s.MediaFramesReceived < 1 || s.MediaBytesReceived < 1 || s.MediaBytesReceived > voiceExpectedMediaByteMax {
		return errors.New("Voice session did not prove bounded returned media")
	}
	if !voiceSHA256.MatchString(s.ReceivedAudioSHA256) {
		return errors.New("Voice returned media hash is absent")
	}
	if s.FirstAudioSeconds <= 0 {
		return errors.New("Voice first returned media timing is absent")
	}
	if s.MediaFramesSent < 1 || s.MediaFramesSent > voiceExpectedFramesMax || !s.IdlePingPong || !s.ForwardClosed {
		return errors.New("Voice session protocol or forward cleanup is incomplete")
	}
	if !recovery && (!s.StopSent || s.CloseCode != 1000 || !s.CloseWasTestInitiated) {
		return errors.New("Voice normal session did not close normally")
	}
	if recovery && (s.StopSent || s.CloseWasTestInitiated) {
		return errors.New("Voice interrupted session was closed by the test")
	}
	if recovery && (!s.ImmediatePreEvictionPingPong || s.Eviction == nil || !s.Eviction.Dispatched || s.Eviction.Disposition != EvictionAccepted) {
		return errors.New("Voice interrupted session lacks an accepted live eviction anchor")
	}
	return nil
}

func voiceFailure(result *VoiceResult, err error) {
	result.Outcome = VoiceOutcomeIncomplete
	if err != nil {
		result.Error = err.Error()
	}
}

func voiceErr(format string, args ...any) error { return fmt.Errorf(format, args...) }
