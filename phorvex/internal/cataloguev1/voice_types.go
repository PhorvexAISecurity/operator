type VoiceMode string

const (
	VoiceNormalMedia         VoiceMode = "normal-media"
	VoiceReplacementRecovery VoiceMode = "replacement-recovery"

	VoiceOutcomeMediaPass       = "PASS_BOUNDED_BIDIRECTIONAL_MEDIA_OBSERVED"
	VoiceOutcomeRecoveryPass    = "PASS_INTERRUPTED_AND_NEW_SESSION_RECOVERED"
	VoiceOutcomeEvictionRefused = "EVICTION_REFUSED_NO_EFFECT"
	VoiceOutcomeEvictionUnknown = "EVICTION_OUTCOME_UNKNOWN_EFFECT_POSSIBLE"
	VoiceOutcomeIncomplete      = "FAIL_OR_INCOMPLETE"
	VoiceAudioSHA256            = "e723680861133e84b20d33a8282540d7d0539bd880bf5d1ccb76b20d14f9adcb"
)

const (
	voiceExpectedFramesMax    = 4500
	voiceExpectedMessagesMax  = 3000
	voiceExpectedMediaByteMax = 2 << 20
)

var (
	voiceDNSLabel = regexp.MustCompile(`^[a-z0-9](?:[-a-z0-9]*[a-z0-9])?$`)
	voiceSHA256   = regexp.MustCompile(`^[0-9a-f]{64}$`)
	voiceDigest   = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)
	voiceID       = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._:-]{0,127}$`)
)

// VoiceConfig is generated by the authenticated console. No field is accepted
// from the browser other than selection of one of the two fixed cases.
type VoiceConfig struct {
	SchemaVersion       string    `json:"schemaVersion"`
	Mode                VoiceMode `json:"mode"`
	OperationID         string    `json:"operationID"`
	OwnerDigest         string    `json:"ownerDigest"`
	Namespace           string    `json:"namespace"`
	DeploymentName      string    `json:"deploymentName"`
	ServiceName         string    `json:"serviceName"`
	PDBName             string    `json:"pdbName"`
	ContainerName       string    `json:"containerName"`
	Port                int32     `json:"port"`
	ExpectedReplicas    int32     `json:"expectedReplicas"`
	MinimumReady        int32     `json:"minimumReady"`
	ExpectedImageDigest string    `json:"expectedImageDigest"`
	BotSourcePath       string    `json:"botSourcePath"`
	BotSourceSHA256     string    `json:"botSourceSHA256"`
	AudioSHA256         string    `json:"audioSHA256"`
}

func (c VoiceConfig) Validate() error {
	if c.SchemaVersion != "phorvex.catalogue.voice.v1" {
		return errors.New("unsupported Voice config schema")
	}
	if c.Mode != VoiceNormalMedia && c.Mode != VoiceReplacementRecovery {
		return errors.New("unsupported Voice mode")
	}
	if !voiceID.MatchString(c.OperationID) || !voiceSHA256.MatchString(c.OwnerDigest) {
		return errors.New("Voice operation identity is incomplete")
	}
	if c.Namespace != "voice" || c.DeploymentName != "voice-bot" || c.ServiceName != "voice-bot" || c.PDBName != "voice-bot" || c.ContainerName != "bot" {
		return errors.New("Voice fixture identity differs from the installed contract")
	}
	if !voiceDNSLabel.MatchString(c.Namespace) || c.Port != 8080 || c.ExpectedReplicas != 3 || c.MinimumReady != 2 {
		return errors.New("Voice fixture bounds differ from the reviewed contract")
	}
	if !voiceDigest.MatchString(c.ExpectedImageDigest) || !voiceSHA256.MatchString(c.BotSourceSHA256) {
		return errors.New("Voice source identity is malformed")
	}
	if c.BotSourcePath != "/app/bot.py" || c.AudioSHA256 != VoiceAudioSHA256 {
		return errors.New("Voice source or audio contract differs")
	}
	return nil
}

